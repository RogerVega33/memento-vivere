import { test, expect } from './fixtures';
import { login, logout, register, saveWords } from './auth-helpers';

test('accounts have private calendars and recovery rotates words, preserves memories and revokes other devices', async ({ page, browser, extraHTTPHeaders }) => {
  test.setTimeout(90000);
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.goto('/');
  await page.getByRole('button', { name: 'Tema claro', exact: true }).click();
  const alice = await register(page);
  await expect(page.getByRole('button', { name: 'Tema claro', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await expect(page.getByRole('heading', { name: 'Toda historia tiene una fecha de inicio' })).toBeVisible();
  await page.getByLabel('Fecha de nacimiento', { exact: true }).fill('2000-01-01');
  await page.getByRole('button', { name: 'Visualizar mi vida' }).click();
  await page.getByRole('button', { name: 'Confirmar y empezar' }).click();
  await expect(page.getByRole('heading', { name: 'El mapa de tu vida' })).toBeVisible();
  await page.getByRole('button', { name: 'Añadir recuerdo' }).click();
  await page.getByLabel('Título').fill('Un recuerdo privado de Alice');
  await page.getByRole('button', { name: 'Guardar recuerdo' }).click();
  await expect(page.getByRole('heading', { name: 'Un recuerdo privado de Alice' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Un recuerdo privado de Alice' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Tema claro', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');

  const remote = await browser.newContext({ baseURL: new URL(page.url()).origin, extraHTTPHeaders });
  try {
    const otherDevice = await remote.newPage();
    await otherDevice.goto('/');
    await login(otherDevice, alice.username, alice.password);
    await expect(otherDevice.getByRole('heading', { name: 'Un recuerdo privado de Alice' })).toBeVisible();
    await logout(page);
    await expect(page.getByRole('button', { name: 'Tema claro', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await register(page);
    await expect(page.getByRole('heading', { name: 'Toda historia tiene una fecha de inicio' })).toBeVisible();
    expect((await (await page.request.get('/api/state')).json()).memoryCount).toBe(0);
    await page.getByLabel('Fecha de nacimiento', { exact: true }).fill('1990-02-02');
    await page.getByRole('button', { name: 'Visualizar mi vida' }).click();
    await page.getByRole('button', { name: 'Confirmar y empezar' }).click();
    await expect(page.getByRole('heading', { name: 'El mapa de tu vida' })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Un recuerdo privado de Alice' })).toHaveCount(0);
    await logout(page);
    await page.getByRole('button', { name: '¿Olvidaste tu contraseña?' }).click();
    await page.getByLabel('Nombre de usuario', { exact: true }).fill(alice.username);
    await page.getByLabel('Palabras de recuperación', { exact: true }).fill(alice.words);
    await page.getByLabel('Nueva contraseña', { exact: true }).fill(alice.password + ' nueva');
    await page.getByLabel('Confirmar contraseña').fill(alice.password + ' nueva');
    await page.getByRole('button', { name: 'Recuperar cuenta', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Guarda tus palabras de recuperación' })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Tema claro', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
    await expect(page.getByText('Estas palabras reemplazan las anteriores', { exact: false })).toBeVisible();
    const renewed = (await page.locator('.recovery-words strong').allTextContents()).join(' ');
    expect(renewed).not.toBe(alice.words);
    await page.setViewportSize({ width: 375, height: 812 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await saveWords(page);
    await expect(page.getByRole('heading', { name: 'Un recuerdo privado de Alice' })).toBeVisible();
    expect((await otherDevice.request.get('/api/state')).status()).toBe(401);
    await otherDevice.reload();
    await expect(otherDevice.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
    await login(otherDevice, alice.username, alice.password);
    await expect(otherDevice.getByRole('alert')).toHaveText('Usuario o contraseña incorrectos.');
    await login(otherDevice, alice.username, alice.password + ' nueva');
    await expect(otherDevice.getByRole('heading', { name: 'Un recuerdo privado de Alice' })).toBeVisible();

    await logout(page);
    await page.getByRole('button', { name: '¿Olvidaste tu contraseña?' }).click();
    await page.getByLabel('Nombre de usuario', { exact: true }).fill(alice.username);
    await page.getByLabel('Palabras de recuperación', { exact: true }).fill(alice.words);
    await page.getByLabel('Nueva contraseña', { exact: true }).fill(alice.password + ' siguiente');
    await page.getByLabel('Confirmar contraseña').fill(alice.password + ' siguiente');
    await page.getByRole('button', { name: 'Recuperar cuenta', exact: true }).click();
    await expect(page.getByRole('alert')).toHaveText('Usuario o palabras de recuperación incorrectos.');
    await page.getByLabel('Palabras de recuperación', { exact: true }).fill(renewed.toUpperCase().replaceAll(' ', '\n'));
    await page.getByRole('button', { name: 'Recuperar cuenta', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Guarda tus palabras de recuperación' })).toBeVisible();
    await saveWords(page);
    await expect(page.getByRole('heading', { name: 'Un recuerdo privado de Alice' })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  } finally { await remote.close(); }
});
