import { test, expect } from './fixtures';
import { login, register } from './auth-helpers';

test('onboarding, calendar, memories, photo deletion and the same account on another device', async ({ page, browser, extraHTTPHeaders }) => {
  const request = page.request;
  await page.goto('/');
  const account = await register(page);
  await expect(page.getByRole('heading', { name: 'Toda historia tiene una fecha de inicio' })).toBeVisible();
  await page.getByLabel('Fecha de nacimiento', { exact: true }).fill('2000-11-30');
  await page.getByRole('button', { name: 'Visualizar mi vida' }).click();
  await expect(page.getByText('Tu fecha de nacimiento será el')).toBeVisible();
  await page.getByRole('button', { name: 'Confirmar y empezar' }).click();
  await expect(page.getByRole('heading', { name: 'El mapa de tu vida' })).toBeVisible();
  await expect(page.locator('.month-cell')).toHaveCount(960);
  await expect(page.locator('.month-cell.selected')).toHaveAttribute('data-current', 'true');
  await expect(page.getByRole('button', { name: 'Añadir recuerdo' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Pantalla completa', exact: true })).toHaveAttribute('aria-expanded', 'false');
  await expect(page.locator('.month-cell.future').first()).toBeDisabled();
  await expect(page.locator('.month-columns span').nth(1)).toHaveText('N');
  await page.locator('[data-index="0"]').hover();
  await expect(page.getByRole('tooltip')).toContainText('noviembre de 2000');
  await expect(page.getByRole('tooltip')).toContainText('Edad: 0 meses');
  await expect(page.getByRole('tooltip')).toContainText('Sin recuerdos');
  await page.locator('[data-index="0"]').focus();
  await page.locator('[data-index="0"]').press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await page.locator('.month-cell.future').first().hover();
  await expect(page.getByRole('tooltip')).toContainText('Por vivir · dentro de 1 mes');
  await expect(page.locator('.month-cell.future').first()).toBeDisabled();
  await page.getByRole('heading', { level: 1 }).hover();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await page.getByRole('button', { name: 'Activar tema oscuro', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: 'Activar tema claro', exact: true }).click();

  await page.locator('[data-index="0"]').click();
  await expect(page.getByRole('heading', { name: 'El mapa de tu vida' })).toBeVisible();
  await expect(page.locator('.month-cell.selected')).toHaveAttribute('data-month', '2000-11');
  await expect(page.locator('.month-cell.selected')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('main')).toHaveCount(1);
  await expect(page.getByRole('button', { name: 'Mes anterior' })).toBeDisabled();
  await page.getByRole('button', { name: 'Añadir recuerdo' }).click();
  await page.getByLabel('Título').fill('El principio');
  await page.getByLabel('Tu recuerdo').fill('Un recuerdo sin día exacto.');
  await page.getByRole('button', { name: 'Guardar recuerdo' }).click();
  await expect(page.getByRole('heading', { name: 'El principio', exact: true })).toBeVisible();
  await expect(page.locator('.memory-date')).toHaveText('noviembre de 2000');
  await expect(page.getByText('Sin día conocido')).toHaveCount(0);

  await page.getByRole('button', { name: 'Añadir recuerdo' }).click();
  await page.getByLabel('Título').fill('Una fecha exacta');
  await page.getByLabel('Día', { exact: true }).fill('30');
  await page.locator('input[type=file]').setInputFiles({ name: 'pixel.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAIAAAD91JpzAAAAEElEQVR4nGM40JAARAwQCgAvDgaB7YfukgAAAABJRU5ErkJggg==', 'base64') });
  await page.getByRole('button', { name: 'Guardar recuerdo' }).click();
  await expect(page.locator('.memory-card h2').first()).toHaveText('Una fecha exacta');
  await page.getByRole('button', { name: 'Pantalla completa', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'El mapa de tu vida' })).toBeVisible();
  await expect(page.getByRole('dialog').locator('.month-cell')).toHaveCount(960);
  await page.locator('[data-index="0"]').hover();
  await expect(page.getByRole('dialog').getByRole('tooltip')).toContainText('2 recuerdos');
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pantalla completa', exact: true })).toBeFocused();
  await expect(page.getByRole('heading', { name: 'Una fecha exacta', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Mes siguiente' }).click();
  await expect(page.locator('.month-cell.selected')).toHaveAttribute('data-month', '2000-12');
  await expect(page.locator('#selected-month-heading')).toHaveText('diciembre 2000');
  await expect(page.getByRole('button', { name: 'Mes siguiente' })).toBeFocused();
  await expect(page.getByRole('button', { name: 'Pantalla completa', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'El mapa de tu vida' })).toBeVisible();
  await page.getByRole('button', { name: 'Mes anterior' }).click();
  await expect(page.locator('.month-cell.selected')).toHaveAttribute('data-month', '2000-11');
  await expect(page.getByRole('heading', { name: 'Una fecha exacta', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Pantalla completa', exact: true }).click();
  await page.getByRole('dialog').press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const photoUrl = await page.locator('.memory-photo img').getAttribute('src');
  expect((await request.get(photoUrl!)).headers()['content-type']).toBe('image/webp');

  const remote = await browser.newContext({ baseURL: new URL(page.url()).origin, extraHTTPHeaders });
  const otherDevice = await remote.newPage();
  await otherDevice.goto('/');
  await expect(otherDevice.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible();
  await login(otherDevice, account.username, account.password);
  await expect(otherDevice.getByRole('heading', { name: 'El mapa de tu vida' })).toBeVisible();
  await expect(otherDevice.locator('.month-cell.selected')).toHaveAttribute('data-current', 'true');
  await otherDevice.locator('[data-index="0"]').click();
  await expect(otherDevice.getByRole('heading', { name: 'Una fecha exacta', exact: true })).toBeVisible();
  await remote.close();

  await page.getByRole('button', { name: 'Opciones de El principio', exact: true }).click();
  await page.getByRole('button', { name: 'Editar El principio', exact: true }).click();
  await page.getByLabel('Título').fill('Un título nuevo');
  await page.getByRole('button', { name: 'Guardar recuerdo' }).click();
  await expect(page.getByRole('heading', { name: 'Un título nuevo' })).toBeVisible();

  await page.getByRole('button', { name: 'Opciones de Una fecha exacta', exact: true }).click();
  await page.getByRole('button', { name: 'Eliminar Una fecha exacta', exact: true }).click();
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Una fecha exacta', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Opciones de Una fecha exacta', exact: true }).click();
  await page.getByRole('button', { name: 'Eliminar Una fecha exacta', exact: true }).click();
  await page.getByRole('button', { name: 'Eliminar recuerdo', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Una fecha exacta', exact: true })).toHaveCount(0);
  expect((await request.get(photoUrl!)).status()).toBe(404);

  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Ir a hoy', exact: true }).click();
  const { today } = await (await request.get('/api/state')).json();
  await expect(page.locator(`[data-index][data-current="true"]`)).toBeFocused();
  await page.locator('[data-current="true"]').click();
  await expect(page.getByRole('button', { name: 'Mes siguiente' })).toBeDisabled();
  const future = `${Number(today.slice(0, 4)) + 1}-01`;
  const rejected = await request.post('/api/memories', { multipart: { payload: JSON.stringify({ title: 'No permitido', year: Number(future.slice(0, 4)), month: 1, day: null }) } });
  expect(rejected.status()).toBe(400);
});
